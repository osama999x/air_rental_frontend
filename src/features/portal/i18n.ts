export function formatStep(template: string, current: number, total: number) {
  return template.replaceAll("{current}", String(current)).replaceAll("{total}", String(total));
}

export function isRtl(code: string) {
  return code === "ar" || code === "ur";
}

export function authCopy(code: string | undefined): AuthCopy {
  return packs[code || "en"] ?? en;
}

export function normalizeLanguage(code: string | null | undefined) {
  return portalLanguages.some((item) => item.code === code) ? code : undefined;
}
