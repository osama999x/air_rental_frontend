export function portalCopy(code: string | null | undefined): PortalCopy {
  const language = normalizeLanguage(code) ?? "en";
  return packs[language] ?? en;
}

export function fillTemplate(template: string, values: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? ""));
}

export function roleTitle(code: string | null | undefined, role: "OWNER" | "TENANT" | "MANAGER") {
  return authCopy(normalizeLanguage(code) ?? "en").roles[role].title;
}
